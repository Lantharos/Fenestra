//! Guest webview types and bridge command names.
//!
//! Guests are secondary Chromium views hosted inside a single
//! [`crate`]-backed window. The app UI (primary webview) creates and
//! controls them via `fenestra.guest.*` bridge commands. Guest pages do
//! not receive the privileged bridge allow-list unless the host
//! explicitly opts in.

